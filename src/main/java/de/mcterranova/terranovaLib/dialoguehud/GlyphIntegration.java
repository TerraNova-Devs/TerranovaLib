package de.mcterranova.terranovaLib.dialoguehud;

import com.nexomc.nexo.NexoPlugin;
import com.nexomc.nexo.glyphs.Glyph;
import com.nexomc.nexo.glyphs.Shift;
import com.nexomc.nexo.glyphs.ShiftTag;
import net.kyori.adventure.key.Key;
import net.kyori.adventure.text.Component;
import net.kyori.adventure.text.TextComponent;
import net.kyori.adventure.text.format.NamedTextColor;
import net.kyori.adventure.text.format.ShadowColor;
import org.betonquest.betonquest.api.common.component.font.Font;
import org.betonquest.betonquest.api.common.component.font.FontRegistry;
import org.bukkit.Bukkit;
import org.jetbrains.annotations.Nullable;

import javax.imageio.ImageIO;
import java.awt.image.BufferedImage;
import java.io.File;
import java.io.IOException;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.function.IntFunction;
import java.util.logging.Logger;

/**
 * The Nexo glyphs the HUD draws, with the width the client gives each of them.
 * <p>
 * The client lays a bitmap glyph out with an advance of {@code round(w * height / textureHeight) + 1},
 * where {@code w} is the column after the rightmost non-transparent pixel of the texture. That is
 * computed here from the very texture Nexo packs, so a replaced texture never leaves the frame
 * misaligned. Every glyph is followed by a one pixel back-shift, which leaves exactly its visible
 * width; the widths are also registered with BetonQuest's font registry so its line wrapper
 * measures icons inside the text correctly.
 * <p>
 * <p>
 * More than one line: the actionbar is a single line, so line {@code i} of {@code n} is drawn in
 * the font of row {@code n - 1 - i}, which draws the vanilla glyphs {@code row * 10} pixels higher
 * (fonts generated by {@code tools/row_fonts.py}). There is one frame per line count, the same ids
 * with {@code _n} appended.
 * <p>
 * Nexo's glyph lookup ({@code NexoPlugin#fontManager}) is not part of its {@code api} package and
 * may move between Nexo versions; verified against Nexo 1.29.1.
 */
final class GlyphIntegration {

    /** A glyph and its visible width in GUI pixels. */
    record Piece(Component component, int width) {
    }

    /**
     * The frame for one line count.
     *
     * @param tiles widest first
     */
    record FrameSet(Piece left, Piece right, List<Piece> tiles) {
    }

    /** Index {@code n - 1} is the frame for {@code n} lines. */
    private final List<FrameSet> frames;

    /** Index {@code r - 1} is the font of text row {@code r} above the actionbar line. */
    private final List<Key> rowFonts;

    private final Map<String, Piece> extras;

    /** A component that moves the cursor by that many pixels without drawing. */
    private final IntFunction<Component> shift;

    GlyphIntegration(final List<FrameSet> frames, final List<Key> rowFonts, final Map<String, Piece> extras,
                     final IntFunction<Component> shift) {
        this.frames = frames;
        this.rowFonts = rowFonts;
        this.extras = extras;
        this.shift = shift;
    }

    /**
     * How many lines a page can have: one per frame, as far as the row fonts reach.
     */
    int maxLines() {
        return Math.min(frames.size(), rowFonts.size() + 1);
    }

    /**
     * Loads the configured glyphs.
     *
     * @return {@code null} when glyphs are disabled, Nexo is not running, or a frame glyph cannot be used
     */
    @Nullable
    static GlyphIntegration load(final HudConfig config, final FontRegistry fonts, final Map<Key, Font> originalFonts,
                                 final Logger log) {
        if (!config.glyphsEnabled()) {
            return null;
        }
        if (!Bukkit.getPluginManager().isPluginEnabled("Nexo")) {
            log.info("Nexo is not running, dialogues use fallback.no-glyphs.");
            return null;
        }
        final Loader loader = new Loader(log);
        final List<FrameSet> frames = new ArrayList<>();
        for (int lines = 1; lines <= config.maxLines(); lines++) {
            final FrameSet frame = loader.frame(config, lines);
            if (frame == null) {
                break;
            }
            frames.add(frame);
        }
        if (frames.isEmpty()) {
            log.warning("The dialogue frame is incomplete, dialogues use fallback.no-glyphs.");
            return null;
        }
        final List<Key> rowFonts = new ArrayList<>();
        for (int row = 1; row < frames.size(); row++) {
            final Key font = Key.key(config.rowFont().replace("{row}", String.valueOf(row)));
            if (!loader.fontExists(font)) {
                break;
            }
            rowFonts.add(font);
        }

        final Map<String, Piece> extras = new HashMap<>();
        final List<String> extraIds = new ArrayList<>(config.npcIcons().values());
        extraIds.add(config.selectorGlyph());
        for (final String id : extraIds) {
            if (!id.isEmpty() && !extras.containsKey(id)) {
                final Piece piece = loader.piece(id);
                if (piece != null) {
                    extras.put(id, piece);
                }
            }
        }
        loader.registerWidths(fonts, originalFonts);
        final FrameSet one = frames.getFirst();
        log.info("Dialogue frame: caps " + one.left().width() + "/" + one.right().width() + " px, middle tiles "
                + one.tiles().stream().map(Piece::width).toList() + " px, " + extras.size() + " extra glyph(s).");
        final GlyphIntegration glyphs = new GlyphIntegration(List.copyOf(frames), List.copyOf(rowFonts),
                Map.copyOf(extras), pixels -> Component.text(Shift.INSTANCE.of(pixels)).font(ShiftTag.INSTANCE.getFONT()));
        log.info("Dialogue lines per page: " + glyphs.maxLines() + " (" + frames.size() + " frame(s), "
                + rowFonts.size() + " row font(s)).");
        return glyphs;
    }

    /**
     * An extra glyph (NPC icon or selector) by its Nexo id.
     */
    @Nullable
    Piece extra(final String id) {
        return extras.get(id);
    }

    /**
     * A single line in the one-line frame.
     */
    Component frame(final Component content, final int contentWidth, final int inner, final int padding) {
        return frame(List.of(content), List.of(contentWidth), 1, inner, padding);
    }

    /**
     * Draws the frame and puts the lines inside it, left-aligned, top to bottom.
     * <p>
     * The frame is drawn first and the cursor is moved back over it, so the text is rendered on top.
     * After each line the cursor returns to the start of the text, and the next line is drawn one row
     * lower. The whole component advances exactly by the frame width, so the client's actionbar
     * centering centers the frame, and a frame of fixed {@code inner} width does not move while text
     * is typed.
     *
     * @param lines   the lines to show, at most {@code rows}
     * @param widths  their widths as measured by BetonQuest's line wrapper
     * @param rows    frame height in lines, at most {@link #maxLines()}; lines start at the top
     * @param inner   the frame's inner width, at least the widest line plus {@code 2 * padding}
     * @param padding space between frame edge and text
     */
    Component frame(final List<Component> lines, final List<Integer> widths, final int rows, final int inner,
                    final int padding) {
        final FrameSet frame = frames.get(rows - 1);
        final Line line = new Line();
        line.glyph(frame.left());
        int remaining = inner;
        for (final Piece tile : frame.tiles()) {
            while (remaining >= tile.width()) {
                line.glyph(tile);
                remaining -= tile.width();
            }
        }
        if (remaining > 0) {
            // No tile fits the rest exactly: overlap the smallest one backwards. Middle tiles
            // are uniform columns, so the overlap is invisible.
            final Piece smallest = frame.tiles().getLast();
            line.shift(remaining - smallest.width());
            line.glyph(smallest);
        }
        line.glyph(frame.right());
        line.shift(-(inner + frame.right().width()) + padding);
        for (int i = 0; i < lines.size(); i++) {
            final int row = rows - 1 - i;
            line.text(row == 0 ? lines.get(i) : Component.text().font(rowFonts.get(row - 1)).append(lines.get(i)).build());
            line.shift(-widths.get(i));
        }
        line.shift(inner - padding + frame.right().width());
        return line.build();
    }

    /**
     * The width the client draws a single-glyph bitmap with, without the 1 px spacing.
     */
    static int visibleWidth(final BufferedImage image, final int glyphHeight) {
        int columns = 0;
        for (int x = image.getWidth() - 1; x >= 0 && columns == 0; x--) {
            for (int y = 0; y < image.getHeight(); y++) {
                if ((image.getRGB(x, y) >>> 24) != 0) {
                    columns = x + 1;
                    break;
                }
            }
        }
        final float scale = (float) glyphHeight / image.getHeight();
        return (int) (0.5 + columns * scale);
    }

    /**
     * Collects components and merges consecutive shifts into one.
     */
    private final class Line {

        private final TextComponent.Builder builder = Component.text();

        private int pendingShift;

        void glyph(final Piece piece) {
            text(piece.component());
            pendingShift -= 1;
        }

        void shift(final int pixels) {
            pendingShift += pixels;
        }

        void text(final Component component) {
            flush();
            builder.append(component);
        }

        Component build() {
            flush();
            return builder.build();
        }

        private void flush() {
            if (pendingShift != 0) {
                builder.append(shift.apply(pendingShift));
                pendingShift = 0;
            }
        }
    }

    /**
     * Reads glyphs from Nexo and measures their textures.
     */
    private static final class Loader {

        private final Logger log;

        private final File packFolder = new File(NexoPlugin.instance().getDataFolder(), "pack/assets");

        /** Font key to codepoint to width as BetonQuest counts it (advance minus its implicit 1 px). */
        private final Map<Key, Map<Integer, Integer>> widths = new HashMap<>();

        Loader(final Logger log) {
            this.log = log;
        }

        /**
         * The frame for this many lines, or {@code null} when one of its glyphs is missing. Missing
         * frames for more lines only limit the line count, so they are not warned about.
         */
        @Nullable
        FrameSet frame(final HudConfig config, final int lines) {
            final String suffix = lines == 1 ? "" : "_" + lines;
            final Piece left = piece(config.frameLeft() + suffix, lines == 1);
            final Piece right = piece(config.frameRight() + suffix, lines == 1);
            final List<Piece> tiles = new ArrayList<>();
            for (final String id : config.frameMiddle()) {
                final Piece tile = piece(id + suffix, lines == 1);
                if (tile != null) {
                    tiles.add(tile);
                }
            }
            if (left == null || right == null || tiles.isEmpty()) {
                return null;
            }
            tiles.sort(Comparator.comparingInt(Piece::width).reversed());
            return new FrameSet(left, right, List.copyOf(tiles));
        }

        /**
         * Whether Nexo's pack folder holds a font definition with this key. Plain pack fonts are no
         * Nexo glyphs, so the file is the only thing to check.
         */
        boolean fontExists(final Key font) {
            return new File(packFolder, font.namespace() + "/font/" + font.value() + ".json").isFile();
        }

        @Nullable
        Piece piece(final String id) {
            return piece(id, true);
        }

        @Nullable
        Piece piece(final String id, final boolean warnIfMissing) {
            final Glyph glyph = NexoPlugin.instance().fontManager().glyphFromID(id);
            if (glyph == null) {
                if (warnIfMissing) {
                    log.warning("Nexo has no glyph '" + id + "'.");
                }
                return null;
            }
            final String chars = String.valueOf(glyph.getChars());
            if (chars.isEmpty()) {
                log.warning("Nexo glyph '" + id + "' has no character.");
                return null;
            }
            final int codepoint = chars.codePointAt(0);
            final File texture = textureFile(glyph.getTexture());
            final BufferedImage image;
            try {
                image = ImageIO.read(texture);
            } catch (final IOException e) {
                log.warning("Cannot read texture " + texture + " of glyph '" + id + "': " + e.getMessage());
                return null;
            }
            if (image == null) {
                log.warning("Texture " + texture + " of glyph '" + id + "' is not an image.");
                return null;
            }
            final int width = visibleWidth(image, glyph.getHeight());
            widths.computeIfAbsent(glyph.getFont(), key -> new HashMap<>()).put(codepoint, width);
            final Component component = Component.text(Character.toString(codepoint))
                    .font(glyph.getFont())
                    .color(NamedTextColor.WHITE)
                    .shadowColor(ShadowColor.none());
            return new Piece(component, width);
        }

        /**
         * Lets BetonQuest's line wrapper measure these glyphs. Its fonts add the 1 px glyph spacing
         * themselves, so the visible width is registered.
         */
        void registerWidths(final FontRegistry fonts, final Map<Key, Font> originalFonts) {
            widths.forEach((key, overrides) -> {
                final Font base = originalFonts.computeIfAbsent(key, fonts::getFont);
                fonts.registerFont(key, codepoint -> {
                    final Integer width = overrides.get(codepoint);
                    return width != null ? width : base.getWidth(codepoint);
                });
            });
        }

        private File textureFile(final Key texture) {
            final String path = texture.value().endsWith(".png") ? texture.value() : texture.value() + ".png";
            return new File(packFolder, texture.namespace() + "/textures/" + path);
        }
    }
}
